#!/usr/bin/env python3
"""
OpenComp Phase 2.1 Step 1 - Independent OpenEXR Reader Verification
Audits the multi-channel EXR generated by Scalable CopyNode using C++ OpenEXR bindings.
Verifies all 8 copied channels + untouched ambient.R + RGBA channels.
"""

import sys
import os
import json
import numpy as np

try:
    import OpenEXR
    import Imath
except ImportError as e:
    print(f"Error importing OpenEXR/Imath: {e}")
    sys.exit(1)

def audit_scalable_copy_exr(exr_path):
    if not os.path.exists(exr_path):
        return {"error": f"File not found: {exr_path}"}

    exr_file = OpenEXR.InputFile(exr_path)
    header = exr_file.header()
    dw = header['dataWindow']
    width = dw.max.x - dw.min.x + 1
    height = dw.max.y - dw.min.y + 1
    channels = header['channels']

    expected_channels = {
        'R': {'type': 'FLOAT'},
        'G': {'type': 'FLOAT'},
        'B': {'type': 'FLOAT'},
        'A': {'type': 'FLOAT'},
        'ambient.R': {'type': 'FLOAT', 'expected_val': 42.5},
        'depth.Z': {'type': 'FLOAT', 'expected_val': 150.25},
        'forward.u': {'type': 'FLOAT', 'expected_val': 1.5},
        'forward.v': {'type': 'FLOAT', 'expected_val': -2.75},
        'diffuse.R': {'type': 'FLOAT', 'expected_val': 0.8},
        'diffuse.G': {'type': 'FLOAT', 'expected_val': 0.6},
        'diffuse.B': {'type': 'FLOAT', 'expected_val': 0.4},
        'specular.R': {'type': 'FLOAT', 'expected_val': 0.95},
        'crypto_object.01': {'type': 'FLOAT', 'expected_val': 1042.0}
    }

    pt = Imath.PixelType(Imath.PixelType.FLOAT)
    channel_results = {}
    all_passed = True

    for ch_name, spec in expected_channels.items():
        if ch_name not in channels:
            channel_results[ch_name] = {"present": False, "error": "Channel missing from EXR header"}
            all_passed = False
            continue

        raw_bytes = exr_file.channel(ch_name, pt)
        arr = np.frombuffer(raw_bytes, dtype=np.float32)
        
        res = {
            "present": True,
            "length": int(len(arr)),
            "min": float(np.min(arr)),
            "max": float(np.max(arr)),
            "mean": float(np.mean(arr))
        }

        if 'expected_val' in spec:
            expected = spec['expected_val']
            max_delta = float(np.max(np.abs(arr - expected)))
            res["expected_val"] = expected
            res["max_delta"] = max_delta
            res["bit_exact"] = bool(max_delta < 1e-5)
            if not res["bit_exact"]:
                all_passed = False
        channel_results[ch_name] = res

    # Check RGBA gradient values
    r_arr = np.frombuffer(exr_file.channel('R', pt), dtype=np.float32).reshape((height, width))
    g_arr = np.frombuffer(exr_file.channel('G', pt), dtype=np.float32).reshape((height, width))
    b_arr = np.frombuffer(exr_file.channel('B', pt), dtype=np.float32)
    a_arr = np.frombuffer(exr_file.channel('A', pt), dtype=np.float32)

    rgba_check = {
        "r_gradient_check": bool(np.isclose(r_arr[0, 0], 0.0) and np.isclose(r_arr[0, width - 1], (width - 1) / width)),
        "g_gradient_check": bool(np.isclose(g_arr[0, 0], 0.0) and np.isclose(g_arr[height - 1, 0], (height - 1) / height)),
        "b_constant_0.5": bool(np.allclose(b_arr, 0.5)),
        "a_constant_1.0": bool(np.allclose(a_arr, 1.0))
    }
    if not all(rgba_check.values()):
        all_passed = False

    audit_summary = {
        "file_path": exr_path,
        "width": width,
        "height": height,
        "total_channels_in_header": len(channels),
        "header_channel_list": sorted(list(channels.keys())),
        "all_expected_channels_present": bool(all(ch_name in channels for ch_name in expected_channels)),
        "channel_preservation_ambient_R_bit_exact": channel_results.get('ambient.R', {}).get('bit_exact', False),
        "copied_8_channels_bit_exact": bool(all(channel_results.get(c, {}).get('bit_exact', False) for c in [
            'depth.Z', 'forward.u', 'forward.v', 'diffuse.R', 'diffuse.G', 'diffuse.B', 'specular.R', 'crypto_object.01'
        ])),
        "rgba_preservation": rgba_check,
        "overall_audit_passed": all_passed,
        "channel_details": channel_results
    }

    return audit_summary

if __name__ == '__main__':
    exr_file = os.path.abspath('tests/final_audit/channels/test_copy_scalable_8ch.exr')
    results = audit_scalable_copy_exr(exr_file)
    
    out_json = os.path.abspath('tests/final_audit/channels/copy_scalable_audit_results.json')
    with open(out_json, 'w') as f:
        json.dump(results, f, indent=2)

    print(json.dumps({
        "status": "PASSED" if results.get("overall_audit_passed") else "FAILED",
        "total_channels": results.get("total_channels_in_header"),
        "channel_preservation_bit_exact": results.get("channel_preservation_ambient_R_bit_exact"),
        "copied_8_channels_bit_exact": results.get("copied_8_channels_bit_exact"),
        "output_json": out_json
    }, indent=2))

